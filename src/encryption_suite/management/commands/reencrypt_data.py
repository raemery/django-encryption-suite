"""
Management command: reencrypt_data

Rotates data encryption keys: moves each silo's encrypted data onto new key
material, then swaps that material in as the silo's own key. Fields first, then
files. See :mod:`encryption_suite.rotation` for the order a run takes and why it
cannot be changed.

A rotation fences the silo's data for the purpose it is rotating: encrypted
reads degrade to the fallback and encrypted writes fail until every row is on
one keyset again. Each run begins with an idle wait of ``DEK_CACHE_TTL`` plus a
margin, so that no process is still holding the old key when conversion starts.

Everything is resumable by rerunning. A run that ends with rows it could not
convert leaves the fence up and says how to leave it: repair the rows and rerun,
or ``--abort`` to put the silo back on its old key. A run that ends with a fence
up, a failed rotation, or (under ``--check``) a value with no digest exits
non-zero, so a scheduler sees it.

The outgoing key is read through the crypto backend its row recorded and the
incoming key is made by ``CRYPTO_BACKEND`` and its options, so after a change of
either a rotation is what moves a silo onto the new backend or algorithm. The dry
run and the opening log line name each such move (``backend tink -> cryptography,
algorithm AES256_GCM_HKDF_4KB -> AES256_GCM_STREAM``). ``--only-outdated``
rotates only the keys with such a move to make.

Usage::

    python manage.py reencrypt_data --dry-run
    python manage.py reencrypt_data --only-outdated
    python manage.py reencrypt_data --silo-uid "team-42"
    python manage.py reencrypt_data --silo-uid "team-42" --purpose field
    python manage.py reencrypt_data --silo-uid "team-42" --abort
    python manage.py reencrypt_data --abort-on-unconvertible
    python manage.py reencrypt_data --purpose index --check
    python manage.py reencrypt_data --format json --output reencrypt_data.json
"""

from __future__ import annotations

from django.core.management.base import BaseCommand, CommandError

from encryption_suite import blind_index, lifecycle
from encryption_suite._internal import optional_log_field
from encryption_suite._logging import get_logger
from encryption_suite.conf import DEFAULT_KEY_SET
from encryption_suite.models import DataEncryptionKey, DekRotation
from encryption_suite.silo_ref import silo_filter

from .._report import Report, add_report_arguments

logger = get_logger(__name__)

#: Outstanding rows printed per purpose before the report summarizes the rest.
_REPORT_LIMIT = 100


def _key_set_suffix(key_set: str) -> str:
    """`` (key set restricted)`` for a non-default key set, and no text for the default."""
    return "" if key_set == DEFAULT_KEY_SET else f" (key set {key_set})"


class Command(BaseCommand):
    help = "Rotate data encryption keys: re-encrypt each silo's data under new key material, then swap it in."

    def add_arguments(self, parser):
        parser.add_argument(
            "--silo-uid",
            dest="silo_uid",
            default=None,
            help="Rotate only this silo. Without it every silo is rotated, which needs a silo adapter "
            "that can enumerate silos.",
        )
        parser.add_argument(
            "--key-set",
            dest="key_set",
            default="default",
            help="Which key set's data keys to rotate: default (the default), system, another key set "
            "declared in KEY_SETS, or all, one pass per key set. Rotating a system key set's keys fences "
            "every column in it while it runs, sign-in included.",
        )
        parser.add_argument(
            "--purpose",
            choices=["field", "file", "index", "all"],
            # None, so --check can tell an omitted --purpose from an explicit one.
            default=None,
            help="Which key to rotate. 'all' (the default) rotates fields, then files, then blind "
            "indexes wherever a field declares one. Naming one rotates only that: a blind index key "
            "is not the key the data is encrypted under, so each can move without the others. "
            "With --check, the default is 'index', the only purpose --check reports on.",
        )
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help="Report what a run would do without fencing, writing, or contacting the KMS.",
        )
        parser.add_argument(
            "--only-outdated",
            dest="only_outdated",
            action="store_true",
            help="Rotate only the data keys generated by another crypto backend or algorithm than "
            "CRYPTO_BACKEND and its options generate now, and count the rest as current. Blind index "
            "keys are never outdated by those settings, so they are skipped.",
        )
        parser.add_argument(
            "--abort",
            action="store_true",
            help="Undo an open rotation: move converted rows back onto the old key, then lower the fence.",
        )
        parser.add_argument(
            "--abort-on-unconvertible",
            action="store_true",
            help="For runs nobody watches: undo the rotation instead of leaving the fence up when a row "
            "cannot be converted. A passing storage error then costs a repeat of the conversion.",
        )
        parser.add_argument(
            "--check",
            action="store_true",
            help=(
                "Report values whose blind index digest was never built, and change nothing. Reads no "
                "key material and contacts no KMS. Exits non-zero while any row is left, so a release "
                "that starts relying on a lookup can be gated on it. Applies to blind indexes only, so "
                "--purpose may be omitted or set to index."
            ),
        )
        parser.add_argument(
            "--show-aad-values",
            action="store_true",
            help="Print the values of AAD-bound columns beside rows that could not be converted. Standard "
            "output only; never logged.",
        )
        add_report_arguments(parser)

    def handle(self, *args, **options):
        if options["purpose"] is None:
            # --check reports on blind indexes only; everything else defaults to every key.
            options["purpose"] = "index" if options["check"] else "all"
        report = Report(self, "reencrypt_data", options, schema_version=1)
        from encryption_suite.conf import key_set_names
        from encryption_suite.rotation_targets import key_sets_in_use

        # One pass per key set: "all" is every key set a field declares. A key set has keys of its own.
        # A pass that ends badly stops the run before the next: a second fence over
        # an unresolved first doubles the outage.
        known = key_set_names()
        if options["key_set"] != "all" and options["key_set"] not in known:
            raise CommandError(
                f"--key-set {options['key_set']!r} is not a declared key set: use all or one of {known}."
            )
        declared = key_sets_in_use()
        key_sets = [each for each in known if each in declared] if options["key_set"] == "all" else [options["key_set"]]

        passes = []
        for key_set in key_sets:
            summary = self._run(key_set, options)
            passes.append(summary)
            if summary["fenced_keys"] or summary["failed"] or sum(summary["values_without_digest"].values()):
                break
        report.write({"passes": passes})
        # After the report, so a scheduler that reads the document also sees the
        # exit status.
        self._raise_for(passes)

    @staticmethod
    def _raise_for(passes) -> None:
        """Turn a run that ended badly into a non-zero exit, naming why."""
        fenced = [entry for each in passes for entry in each["fenced_keys"]]
        if fenced:
            listed = ", ".join(f"{entry['silo_uid']} [{entry['purpose']}]" for entry in fenced)
            raise CommandError(
                f"Stopped with the fence up: {listed}. Encrypted reads and writes of that data stay blocked until "
                "the rotation is finished or aborted — see the report above."
            )
        unbuilt = sum(sum(each["values_without_digest"].values()) for each in passes)
        if unbuilt:
            raise CommandError(
                f"{unbuilt} value(s) hold no digest, so no lookup can find them. Build the digests before "
                "a release relies on one: setup_encryption_keys to provision the index key where a silo "
                "has none, then reencrypt_data --purpose index."
            )
        failed = sum(each["failed"] for each in passes)
        if failed:
            raise CommandError(
                f"{failed} rotation(s) failed. Each is named in a 'Failed:' line above, and the run stopped there."
            )

    @staticmethod
    def _summary(key_set, options, conversions, *, tally=None, fenced=(), unbuilt=None) -> dict:
        """One pass's summary, for the JSON report and for the exit status."""
        tally = tally or {}
        return {
            "key_set": key_set,
            "purpose": options["purpose"],
            "silo_uid": options["silo_uid"],
            "dry_run": options["dry_run"],
            "abort": options["abort"],
            "check": bool(options["check"]),
            "only_outdated": options["only_outdated"],
            "converts": conversions,
            "rotated": tally.get("rotated", 0),
            "abandoned": tally.get("abandoned", 0),
            "skipped": tally.get("skipped", 0),
            "current": tally.get("current", 0),
            "fenced": tally.get("fenced", 0),
            "failed": tally.get("failed", 0),
            "fenced_keys": [
                {"key_set": ref.key_set, "silo_uid": ref.uid, "purpose": purpose} for ref, purpose in fenced
            ],
            "values_without_digest": unbuilt or {},
        }

    def _run(self, key_set: str, options) -> dict:
        """Run one pass, for one key set, and return its summary."""
        from encryption_suite.conf import is_system_key_set
        from encryption_suite.registry import get_engine, get_silo_adapter
        from encryption_suite.rotation_targets import encrypted_models, resolve_targets
        from encryption_suite.user_context import get_os_user, identity_tail

        os_login_user = get_os_user()
        silo_uid = options["silo_uid"]
        dry_run = options["dry_run"]
        abort = options["abort"]
        purpose = options["purpose"]
        if silo_uid and is_system_key_set(key_set):
            raise CommandError(
                "--silo-uid names one of the silos, and a system key set has one silo already. Pass "
                "--silo-uid with another key set."
            )
        only_outdated = options["only_outdated"]
        conversions = "" if abort or options["check"] else self._conversions(silo_uid, purpose, key_set)
        # Before any validation, so a refused run is on record too.
        logger.warning(
            "A privileged management command started; this line records that it ran, including a run that "
            "changes nothing. command=reencrypt_data key_set=%s dry_run=%s abort=%s check=%s "
            'only_outdated=%s purpose=%s silo="%s"%s %s',
            key_set,
            dry_run,
            abort,
            bool(options["check"]),
            only_outdated,
            purpose,
            silo_uid or "all",
            optional_log_field("converts", conversions),
            identity_tail(os_login_user=os_login_user),
        )
        if only_outdated and (abort or options["check"]):
            raise CommandError(
                "--only-outdated chooses which keys to rotate. --abort reverses a rotation already open and "
                "--check rotates nothing, so neither takes it."
            )
        if conversions:
            self.stdout.write(f"{'[dry-run] ' if dry_run else ''}Converting: {conversions}")
        self.show_aad_values = options["show_aad_values"]
        if self.show_aad_values and not self.stdout.isatty():
            self.stderr.write(
                self.style.WARNING(
                    "--show-aad-values prints bound-column values, and standard output is not a terminal: they "
                    "are going to a file or a pipe."
                )
            )

        if options["check"]:
            # Before the engine and the adapter are touched at all: a digest that
            # is absent is a property of the row, so the scan needs no key, no
            # silo and no KMS, and has to stay runnable on a deployment where the
            # KMS is exactly what is broken.
            self._validate_check(purpose, silo_uid, dry_run, abort, options)
            return self._summary(key_set, options, conversions, unbuilt=self._check_digests(key_set))

        engine = get_engine()
        adapter = get_silo_adapter(key_set)
        resolution = resolve_targets(adapter, models=list(encrypted_models(key_set)))
        if purpose == "all":
            purposes = [DataEncryptionKey.PURPOSE_FIELD, DataEncryptionKey.PURPOSE_FILE]
            # Only where something is indexed. A deployment with no blind index
            # has no third key to move, and reporting one skipped per silo would
            # be noise on every routine run. Naming the purpose still asks for
            # it, and still answers that there is no such key.
            if any(True for _model, _field in blind_index.silo_indexed_fields(key_set=key_set)):
                purposes.append(DataEncryptionKey.PURPOSE_INDEX)
        else:
            purposes = [purpose]
        if only_outdated and DataEncryptionKey.PURPOSE_INDEX in purposes:
            purposes.remove(DataEncryptionKey.PURPOSE_INDEX)
            self.stdout.write(
                f"{'[dry-run] ' if dry_run else ''}Skipped: every [index] key — a blind index key is HMAC-SHA-256 "
                "whatever CRYPTO_BACKEND and its options are, so --only-outdated never finds one outdated."
            )
        silos = self._silos(adapter, key_set, silo_uid)
        if is_system_key_set(key_set) and not dry_run:
            self.stdout.write(
                self.style.WARNING(
                    "Rotating a system key set's keys: every column in it, sign-in included, "
                    "is unreadable until each purpose's swap."
                )
            )

        # Every ending below closes the run on a log line. The rotation's own
        # lines close each *rotation*; this one closes the command, which is a
        # different thing on a run over many silos — and the only thing at all
        # on a run that rotated nothing.
        tally = dict.fromkeys(("rotated", "abandoned", "skipped", "fenced", "failed", "current"), 0)

        def log_finished():
            """Close the run, at the level its opening line was written at.

            Called from every ending the command reaches on purpose — including a
            refusal, and a stop with the fence up. An opening line with no closing
            line after it is a run that did not reach an ending it knows about.
            """
            logger.warning(
                "A privileged management command finished. command=reencrypt_data key_set=%s "
                'dry_run=%s abort=%s purpose=%s silo="%s" rotated=%d abandoned=%d skipped=%d fenced=%d '
                "failed=%d current=%d %s",
                key_set,
                dry_run,
                abort,
                purpose,
                silo_uid or "all",
                tally["rotated"],
                tally["abandoned"],
                tally["skipped"],
                tally["fenced"],
                tally["failed"],
                tally["current"],
                identity_tail(os_login_user=os_login_user),
            )

        if dry_run:
            self._dry_run(
                engine,
                adapter,
                resolution,
                silos,
                purposes,
                key_set=key_set,
                abort=abort,
                only_outdated=only_outdated,
                tally=tally,
            )
            log_finished()
            return self._summary(key_set, options, conversions, tally=tally)
        # Refused before any fence goes up, so there is nothing to roll back. An
        # abort needs no resolution: it walks the rows the worklist recorded.
        if resolution.unresolved and not abort:
            log_finished()
            raise CommandError(self._unresolved_message(resolution))

        from encryption_suite.exceptions import EncryptionError
        from encryption_suite.rotation import (
            FENCED_OUTCOMES,
            OUTCOME_ABANDONED,
            OUTCOME_SKIPPED,
            OUTCOME_SWAPPED,
            Rotator,
        )

        # Every state that is not one of these three left the silo fenced, which
        # is the one result a run must not report as an ordinary ending.
        tallied_as = {
            OUTCOME_SWAPPED: "rotated",
            OUTCOME_ABANDONED: "abandoned",
            OUTCOME_SKIPPED: "skipped",
        }

        rotator = Rotator(
            engine=engine,
            adapter=adapter,
            resolution=resolution,
            os_login_user=os_login_user,
            write=self._write,
        )
        fenced = []
        stop = False
        for uid, silo in silos:
            with self._scope(adapter, uid):
                if silo is None and resolution.needs_silo_object and not abort:
                    silo = adapter.silo_for_uid(uid.uid)
                    if silo is None:
                        log_finished()
                        raise CommandError(self._no_silo_message(uid.uid))
                for each in purposes:
                    if only_outdated and self._report_current(rotator, uid, each, key_set):
                        tally["current"] += 1
                        continue
                    try:
                        outcome = rotator.run(
                            uid,
                            each,
                            silo,
                            abort=abort,
                            abort_on_unconvertible=options["abort_on_unconvertible"],
                        )
                    except EncryptionError as exc:
                        self._report_failure(uid, each, exc)
                        tally["failed"] += 1
                        if self._is_fenced(uid, each, key_set):
                            fenced.append((uid, each))
                        stop = True
                        break
                    self._report(outcome, key_set)
                    tally[tallied_as.get(outcome.state, "fenced")] += 1
                    if outcome.state in FENCED_OUTCOMES:
                        # A second fence over an unresolved first doubles the
                        # outage and leaves --abort two rotations to choose between.
                        fenced.append((uid, each))
                        stop = True
                        break
                    if outcome.state == OUTCOME_ABANDONED and outcome.detail == lifecycle.REASON_UNCONVERTIBLE_ROWS:
                        stop = True
                        break
            if stop:
                break

        log_finished()
        if not fenced:
            self.stdout.write("Done.")
        return self._summary(key_set, options, conversions, tally=tally, fenced=fenced)

    # ------------------------------------------------------------------
    # Digests that were never built
    # ------------------------------------------------------------------

    @staticmethod
    def _validate_check(purpose, silo_uid, dry_run, abort, options):
        """Refuse a ``--check`` whose other flags say it is something else."""
        if purpose != "index":
            # Refused rather than ignored: a scan of the digests passing under
            # --purpose field would read as the field keys having been checked.
            raise CommandError("--check reports blind index digests only; drop --purpose or pass --purpose index.")
        if silo_uid:
            raise CommandError(
                "--check takes no --silo-uid: an absent digest is a property of the row, and the scan "
                "reads nothing a silo would scope."
            )
        if dry_run or abort or options["abort_on_unconvertible"]:
            raise CommandError(
                "--check already changes nothing. Pass it without --dry-run, --abort or --abort-on-unconvertible."
            )

    def _check_digests(self, key_set: str) -> dict[str, int]:
        """Report indexed values holding no digest; return the count per column.

        The caller exits non-zero when any count is above zero.

        What this catches is an adoption that stopped at the column change.
        ``encrypt_field`` converts the value and leaves the digest alone — it
        cannot do otherwise, because the migration that calls it runs while the
        column is still declared as a plain ``TextField``, with no
        ``blind_index`` to read and, under the default storage, no digest column
        to write to yet. So the rows come out encrypted and unfindable, and a
        lookup against them matches nothing rather than failing, which reads as
        "no such row".

        A digest absent is the only thing judged here. Whether a digest is
        *current* cannot be: nothing records which index key wrote one, so
        telling a live digest from one written under a key on its way out means
        decrypting every value — which is a rotation, is fenced, and is what
        ``--purpose index`` does without ``--check``.
        """
        from encryption_suite import blind_index

        targets = list(blind_index.silo_indexed_fields(key_set=key_set))
        if not targets:
            self.stdout.write(f"No encrypted column of key_set={key_set!r} declares a blind index. Nothing to check.")
            return {}

        counts = {}
        for owner, field in targets:
            column = f"{owner._meta.label}.{field.name}"
            counts[column] = self._unbuilt(owner, field)
            self.stdout.write(f"{column}: {counts[column]} value(s) with no digest")

        self.stdout.write("")
        if not sum(counts.values()):
            self.stdout.write(self.style.SUCCESS("Every indexed value has a digest."))
        return counts

    @staticmethod
    def _unbuilt(owner, field) -> int:
        """How many of *field*'s values have no digest recorded anywhere.

        Nothing is decrypted and no lookup is built by value: the stored column
        is read as it stands, which is what it would be worth to an attacker and
        all this needs. A value lookup would be rewritten against the very index
        being judged.
        """
        from encryption_suite.fields import BLIND_INDEX_STORAGE_COLUMN
        from encryption_suite.migration_helpers import _iter_rows_with_columns
        from encryption_suite.models import BlindIndexEntry

        recorded = None
        if field.blind_index_storage != BLIND_INDEX_STORAGE_COLUMN:
            # One query for the whole column rather than one per row: the digests
            # live in a table of their own, and asking it per row would walk it
            # once for every value.
            recorded = set(
                BlindIndexEntry.objects.filter(
                    model_label=owner._meta.label,
                    field_name=field.name,
                ).values_list("object_pk", flat=True)
            )

        unbuilt = 0
        # The base manager, never the default one: a manager that filters would
        # hide the rows nothing can find, which are the rows being counted.
        for row, columns in _iter_rows_with_columns(owner, owner._base_manager.all(), [field.name], 500):
            stored = columns[field.name]
            if stored is None or stored == "":
                # Nothing to index, so no digest is owed.
                continue
            if recorded is None:
                if getattr(row, field.index_field_name) is None:
                    unbuilt += 1
            elif str(row.pk) not in recorded:
                unbuilt += 1
        return unbuilt

    # ------------------------------------------------------------------
    # Which silos
    # ------------------------------------------------------------------

    @staticmethod
    def _scope(adapter, uid):
        """The adapter's scope for *uid*'s rows."""
        return adapter.use_silo(uid.uid)

    def _silos(self, adapter, key_set, silo_uid):
        """``[(silo reference, silo or None)]`` for the run.

        A partial list is worse than none, so a run without ``--silo-uid`` needs
        an adapter that can list every silo — not merely the ones it happens to
        see.
        """
        from encryption_suite.silo_ref import SiloRef

        if silo_uid:
            return [(SiloRef(key_set, silo_uid), None)]
        if not adapter.supports_enumeration:
            raise CommandError(
                f"The silo adapter '{type(adapter).__name__}' cannot list every silo, so this command can rotate "
                "only one silo per run. Pass --silo-uid."
            )
        return [(SiloRef(key_set, adapter.get_silo_uid(silo)), silo) for silo in adapter.iter_silos()]

    @staticmethod
    def _unresolved_message(resolution) -> str:
        listed = "; ".join(f"{label} ({why})" for label, why in resolution.unresolved)
        return (
            f"Refusing to rotate: cannot find which rows belong to a silo for {listed}. Their data would stay "
            "on the old key, and the swap destroys it. Give each model exactly one foreign key to the silo "
            "adapter's model_label model, or set supports_silo_data_lookup = True on the silo adapter and "
            "implement queryset_for_silo(). Nothing was fenced."
        )

    @staticmethod
    def _no_silo_message(uid) -> str:
        return (
            f"Refusing to rotate: silo UID '{uid}' resolves to no silo. The silo adapter's silo_for_uid() "
            "answers this — its default needs supports_enumeration, so an adapter that cannot enumerate must "
            "override it. Nothing was fenced."
        )

    def _report_current(self, rotator, uid, purpose, key_set, prefix="") -> bool:
        """Report and answer true when *uid*'s key for *purpose* is current, for ``--only-outdated``.

        Only an active key can be current. An open rotation is left to the
        rotator, which resumes it, and a missing key to its own skip line.
        """
        dek = DataEncryptionKey.objects.filter(**silo_filter(uid), purpose=purpose).first()
        if dek is None or dek.status != lifecycle.STATUS_ACTIVE or rotator.key_conversion(dek):
            return False
        self.stdout.write(
            f"{prefix}Current: {uid} [{purpose}] — backend {dek.crypto_backend}, algorithm {dek.algorithm}"
        )
        return True

    @staticmethod
    def _is_fenced(uid, purpose, key_set) -> bool:
        return DataEncryptionKey.objects.filter(
            **silo_filter(uid), purpose=purpose, status=lifecycle.STATUS_REENCRYPTING
        ).exists()

    # ------------------------------------------------------------------
    # Output
    # ------------------------------------------------------------------

    def _write(self, text, style=None):
        styler = {"success": self.style.SUCCESS, "warning": self.style.WARNING, "error": self.style.ERROR}.get(style)
        self.stdout.write(styler(text) if styler else text)

    def _report_failure(self, uid, purpose, exc):
        detail = getattr(exc, "detail", "") or str(exc)
        self.stderr.write(self.style.ERROR(f"Failed: {uid} [{purpose}] [{exc.code}]: {detail}"))

    def _report(self, outcome, key_set):
        from encryption_suite import rotation

        where = f"{outcome.silo_ref} [{outcome.purpose}]{_key_set_suffix(key_set)}"
        if outcome.state == rotation.OUTCOME_SKIPPED:
            self.stdout.write(f"Skipped: {where} — {outcome.detail}")
        elif outcome.state == rotation.OUTCOME_SWAPPED:
            self._write(f"Rotated: {where} — {outcome.converted} item(s) converted, key swapped in.", "success")
        elif outcome.state == rotation.OUTCOME_ABANDONED:
            self._write(
                f"Abandoned: {where} — {outcome.converted} item(s) moved back; the old key is in use.", "success"
            )
        else:
            self._report_open(outcome, key_set)

    def _report_open(self, outcome, key_set):
        """The report for a purpose left fenced — the operator's only view of that state."""
        from encryption_suite import rotation

        dek = DataEncryptionKey.objects.get(**silo_filter(outcome.silo_ref), purpose=outcome.purpose)
        backward = outcome.state == rotation.OUTCOME_ROLLBACK_OUTSTANDING or (
            DekRotation.objects.filter(dek=dek, rolling_back=True).exists()
        )
        where = f"{outcome.silo_ref} [{outcome.purpose}]{_key_set_suffix(key_set)}"
        moved = "moved back" if backward else "converted"
        self._write(
            f"Fenced: {where} — {outcome.converted} item(s) {moved} this run, {outcome.outstanding} outstanding. "
            "Encrypted reads and writes of this data stay blocked.",
            "warning",
        )
        if outcome.detail:
            self._write(f"  {outcome.detail}", "warning")
        items = rotation.converted_items(dek) if backward else rotation.outstanding_items(dek)
        self._print_items(items)
        base = (
            f'python manage.py reencrypt_data --key-set {outcome.silo_ref.key_set} --silo-uid "{outcome.silo_ref.uid}" '
            f"--purpose {outcome.purpose}"
        )
        if backward:
            self.stdout.write(
                "  The rollback continues where it stopped on a rerun, once the cause is dealt with:\n"
                f"    {base} --abort"
            )
        else:
            self.stdout.write(
                "  Two ways out. A failure that is not the row's own — a storage timeout, an unreachable provider — "
                "clears on a rerun alone; a changed or emptied AAD-bound column, ciphertext that no longer "
                "authenticates, or a row in the wrong silo needs repairing in the application first.\n"
                "  1. Repair and rerun. Rows already converted stay converted:\n"
                f"    {base}\n"
                "  2. Abort, putting the silo back on its old key while the rows are repaired at leisure:\n"
                f"    {base} --abort"
            )

    def _print_items(self, items):
        from encryption_suite.rotation import aad_columns_for, render_aad

        total = items.count()
        for item in items[:_REPORT_LIMIT]:
            aad = render_aad(
                aad_columns_for(item.model_label, item.object_pk, item.field_name), show_values=self.show_aad_values
            )
            self.stdout.write(
                f"  {item.model_label} pk={item.object_pk} {item.field_name}"
                f" — {item.failure_code or 'not attempted'}{f' — aad: {aad}' if aad else ''}"
            )
        if total > _REPORT_LIMIT:
            self.stdout.write(
                f"  … and {total - _REPORT_LIMIT} more. The worklist keeps them all while the rotation is open; "
                "a --dry-run reprints this report."
            )

