    @staticmethod
    def _conversions(silo_uid, purpose, key_set) -> str:
        """Each distinct backend and algorithm move this run would make, joined by ``; ``, or ``""``.

        Each move is worded by :func:`~encryption_suite.rotation.key_conversion`,
        the function the dry run marks each key with, so the opening line, the
        ``Converting:`` line and the dry run cannot disagree. Read before
        anything else runs, for the opening line, so a backend that cannot be
        built leaves the line without the field rather than stopping a run that
        may never need it.
        """
        from encryption_suite.exceptions import EncryptionError
        from encryption_suite.registry import get_crypto_backend
        from encryption_suite.rotation import key_conversion

        try:
            configured = get_crypto_backend()
        except EncryptionError:
            return ""
        qs = DataEncryptionKey.objects.filter(status=lifecycle.STATUS_ACTIVE).exclude(
            purpose__in=[DataEncryptionKey.PURPOSE_TEST, DataEncryptionKey.PURPOSE_INDEX]
        )
        qs = qs.filter(key_set=key_set)
        if silo_uid:
            qs = qs.filter(silo_uid=silo_uid)
        if purpose != "all":
            qs = qs.filter(purpose=purpose)
        stored = set(qs.values_list("purpose", "crypto_backend", "algorithm").distinct())
        moves = {key_conversion(*each, configured) for each in stored}
        return "; ".join(sorted(move for move in moves if move))

    def _dry_run(self, engine, adapter, resolution, silos, purposes, *, key_set, abort, only_outdated, tally):
        """Report what a run would do. Never fences, never writes, never touches the KMS."""
        from encryption_suite import rotation

        prefix = "[dry-run] "
        for target in resolution.targets:
            how = f"filtered on {target.fk_name}" if target.fk_name else "rows from the silo adapter"
            self.stdout.write(f"{prefix}Model: {target.label} ({how})")
        for label, why in resolution.unresolved:
            self._write(f"{prefix}Unresolved: {label} ({why}) — a real run refuses until this is fixed.", "warning")
        self.stdout.write(
            f"{prefix}Conversion starts after an idle wait of {rotation.wait_seconds()}s per purpose, while the "
            "silo is fenced."
        )

        rotator = rotation.Rotator(
            engine=engine, adapter=adapter, resolution=resolution, os_login_user="", write=self._write
        )
        for uid, silo in silos:
            with self._scope(adapter, uid):
                if silo is None and resolution.needs_silo_object:
                    silo = adapter.silo_for_uid(uid.uid)
                    if silo is None:
                        self._write(
                            f"{prefix}Unresolved silo: {uid.uid} resolves to no silo — the silo adapter's "
                            "silo_for_uid() would answer it.",
                            "warning",
                        )
                for each in purposes:
                    if only_outdated and self._report_current(rotator, uid, each, key_set, prefix):
                        tally["current"] += 1
                        continue
                    state = self._dry_run_purpose(
                        rotator, resolution, adapter, uid, silo, each, key_set=key_set, abort=abort, prefix=prefix
                    )
                    tally[state] += 1

    def _dry_run_purpose(self, rotator, resolution, adapter, uid, silo, purpose, *, key_set, abort, prefix) -> str:
        """Report what this silo and purpose would do, and answer how to count it.

        The answer uses the same words a real run's closing line uses, so a
        preview and the run it previews are read the same way — "fenced" for an
        open rotation, because that is what the silo already is.
        """
        from encryption_suite import rotation
        from encryption_suite.rotation_targets import rows_for_silo

        where = f"{uid} [{purpose}]{_key_set_suffix(key_set)}"
        dek = DataEncryptionKey.objects.select_related("kek").filter(**silo_filter(uid), purpose=purpose).first()
        if dek is None:
            self.stdout.write(f"{prefix}Skipped: {where} — no data encryption key for this purpose")
            return "skipped"
        open_rotation = DekRotation.objects.filter(dek=dek).first()
        if dek.status == lifecycle.STATUS_REENCRYPTING and open_rotation is not None:
            if abort or open_rotation.rolling_back:
                count = rotation.converted_items(dek).count()
                self.stdout.write(f"{prefix}Would roll back: {where} — {count} item(s) to move back onto the old key")
                return "abandoned"
            outstanding = rotation.outstanding_items(dek)
            self._write(
                f"{prefix}Open rotation: {where} — {outstanding.count()} item(s) outstanding"
                f"{'' if open_rotation.worklist_complete else ' (worklist not yet built)'}",
                "warning",
            )
            self._print_items(outstanding)
            return "fenced"
        if abort:
            self.stdout.write(f"{prefix}Skipped: {where} — no rotation is open")
            return "skipped"
        if dek.status != lifecycle.STATUS_ACTIVE:
            self.stdout.write(f"{prefix}Skipped: {where} — data encryption key is {dek.status}")
            return "skipped"
        refusal = rotator.open_refusal(dek)
        if refusal:
            self.stdout.write(f"{prefix}Skipped: {where} — {refusal}")
            return "skipped"
        conversion = rotator.key_conversion(dek)
        self.stdout.write(f"{prefix}Would rotate: {where}{f' ({conversion})' if conversion else ''}")
        for target in resolution.for_purpose(purpose, key_set):
            if target.fk_name and silo is None:
                continue
            count = rows_for_silo(adapter, target, uid.uid, silo).count()
            # A snapshot, not a promise: rows come and go until the fence is up.
            self.stdout.write(f"{prefix}  {target.label}: {count} row(s) now")
        return "rotated"
